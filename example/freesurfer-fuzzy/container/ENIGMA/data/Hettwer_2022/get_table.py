# Create DataFrame, format like ENIGMA
data["ROI"] = [roi.replace("L","L_").replace("R","R_") for roi in data["ROI"]]
data["ROI"] = ["".join(roi.split()) for roi in data["ROI"]]
df = pd.DataFrame(data)
df = df.melt(id_vars=["ROI"], var_name="Disorder", value_name="Cohen_d")
df.rename(columns={"ROI": "Structure"}, inplace=True)
for disorder in df["Disorder"].unique():
  df_disorder = df[df["Disorder"] == disorder]
  df_disorder = df_disorder[["Structure", "Cohen_d"]]
  df_disorder.to_csv(root_dir / f"{disorder.lower()}_cohen_d.csv", index=False)